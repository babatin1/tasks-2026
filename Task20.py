print("Ты проснулся в таинственном лесу. Перед тобой две тропинки.")
step1 = input("Пойти налево (1) или направо (2)? ")

if step1 == "1":
    # Ветка налево
    step2_left = input("Ты вышел к темной пещере. Зайти внутрь (1) или пройти мимо (2)? ")
    
    if step2_left == "1":
        print("Внутри пещеры ты нашел сундук с золотом! Ты стал богачом. (Концовка 1: Богатство)")
    elif step2_left == "2":
        print("Ты прошел мимо и наткнулся на дикого волка. Пришлось убегать! (Концовка 2: Побег)")
    else:
        print("Ты стоял в нерешительности и замерз. (Концовка 3: Плохой конец)")

elif step1 == "2":
    # Ветка направо
    step2_right = input("Ты вышел к бурной реке. Попытаться переплыть (1) или построить плот (2)? ")
    
    if step2_right == "1":
        print("Течение унесло тебя в водопад, но ты выжил и нашел волшебный амулет. (Концовка 4: Чудо)")
    elif step2_right == "2":
        print("Ты построил отличный плот и доплыл до цивилизации. (Концовка 5: Спасение)")
    else:
        print("Пока ты думал, река обмелела, и ты перешел ее пешком. (Концовка 6: Скука)")

else:
    print("Ты не понял, куда идти, сел на пенек и застрял в лесу навсегда. (Концовка 7: Тупик)")